#!/bin/sh
#
# Regenerates src/ps3_gpu_shaders.h. NOT part of the normal build: the
# header is in the tree, so building the game needs neither of these tools.
#
# Needs:
#   cgc      NVIDIA Cg Toolkit 3.1, Linux build (apt install nvidia-cg-toolkit)
#   cgcomp   PSL1GHT's, only its assembler mode (-a): $PS3DEV/bin/cgcomp
#   python3
#
# cgc turns Cg into NV40 assembly (profiles vp40 / fp40), cgcomp -a turns
# the assembly into the .vpo/.fpo binaries PSL1GHT loads (the method of
# TyrQuakeCell and Quake2PS3).
#
#   cd ps3/shaders && sh build_shaders.sh

set -e

CGC=${CGC:-cgc}
CGCOMP=${CGCOMP:-$PS3DEV/bin/cgcomp}

command -v "$CGC" >/dev/null 2>&1 || { echo "cgc not found (apt install nvidia-cg-toolkit)"; exit 1; }
[ -x "$CGCOMP" ] || { echo "cgcomp not found at $CGCOMP"; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$CGC" -quiet -profile vp40 -o "$TMP/r3d_vp.asm" r3d_vp.vcg
"$CGCOMP" -a -v "$TMP/r3d_vp.asm" "$TMP/r3d_vp.vpo" >/dev/null

# cgc's fp40 code names half registers (H0, H1...) apart from the full
# ones (R0...), as the NV driver allocates them; cgcomp -a puts Hn in half
# of R(n/2) instead, so H0 overwrites R0.xy and the program computes
# garbage on the RSX (the light by distance, the smooth filter's texture
# coordinates). Each Hn becomes a full register of its own first.
NoHalfRegs()
{
	python3 - "$1" <<'PYEOF'
import re, sys
path = sys.argv[1]
asm = open(path).read()
rs = [int(n) for n in re.findall(r'^TEMP R(\d+);', asm, re.M)]
base = max(rs) + 1 if rs else 0
hs = sorted(set(int(n) for n in re.findall(r'^SHORT TEMP H(\d+);', asm, re.M)))
for h in hs:
    asm = asm.replace('SHORT TEMP H%d;' % h, 'TEMP R%d;' % (base + h))
asm = re.sub(r'\bH(\d+)\b', lambda m: 'R%d' % (base + int(m.group(1))), asm)
assert not re.search(r'\bH\d', asm)
open(path, 'w').write(asm)
PYEOF
}

# cgcomp -a sets "perspective correction off" on every DP2/DP3/DP4/MUL/
# DIV/NRM that reads a texture coordinate input; the RSX then hands that
# instruction the coordinate divided by the clip w (on the world's
# triangles, close to 0: the light, the smooth filter's texture size, the
# depth). Only those instructions do it, so each coordinate the program
# reads is copied once into a register of its own at the start (a MOV
# keeps the correction) and the program reads the copies.
CorrectInputs()
{
	python3 - "$1" <<'PYEOF'
import re, sys
path = sys.argv[1]
asm = open(path).read()
tcs = sorted(set(int(n) for n in re.findall(r'fragment\.texcoord\[(\d+)\]', asm)))
if tcs:
    rs = [int(n) for n in re.findall(r'^TEMP R(\d+);', asm, re.M)]
    base = max(rs) + 1 if rs else 0
    regs = dict((tc, 'R%d' % (base + i)) for i, tc in enumerate(tcs))
    lines = asm.split('\n')
    first = next(i for i, l in enumerate(lines)
                 if re.match(r'^[A-Z][A-Z0-9_]*\s', l) and not re.match(r'^(TEMP|SHORT|PARAM|OUTPUT|OPTION)\b', l))
    body = '\n'.join(lines[first:])
    body = re.sub(r'fragment\.texcoord\[(\d+)\]', lambda m: regs[int(m.group(1))], body)
    head = lines[:first]
    head += ['TEMP %s;' % regs[tc] for tc in tcs]
    head += ['MOVR  %s, fragment.texcoord[%d];' % (regs[tc], tc) for tc in tcs]
    asm = '\n'.join(head) + '\n' + body
open(path, 'w').write(asm)
PYEOF
}

FPS="r3d_fp_world r3d_fp_smooth r3d_fp_rgba r3d_fp_color"
for fp in $FPS; do
	"$CGC" -quiet -profile fp40 -o "$TMP/$fp.asm" $fp.fcg
	NoHalfRegs "$TMP/$fp.asm"
	CorrectInputs "$TMP/$fp.asm"
	"$CGCOMP" -a -f "$TMP/$fp.asm" "$TMP/$fp.fpo" >/dev/null
done

python3 - "$TMP" r3d_vp $FPS <<'PYEOF'
import sys
tmp = sys.argv[1]
names = sys.argv[2:]
out = ["/* ps3_gpu_shaders.h -- GENERATED by shaders/build_shaders.sh, don't edit.",
       " * Compiled RSX programs (cgc vp40/fp40 + PSL1GHT cgcomp -a) of the Cg",
       " * sources in shaders/. */",
       "",
       "#ifndef PS3_GPU_SHADERS_H",
       "#define PS3_GPU_SHADERS_H",
       ""]
for n in names:
    ext = ".vpo" if n.endswith("_vp") else ".fpo"
    data = open(tmp + "/" + n + ext, "rb").read()
    out.append("static const unsigned char %s%s[] __attribute__((aligned(16))) = {" % (n, ext.replace(".", "_")))
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
    out.append("};")
    out.append("")
out.append("#endif")
open("../source/ps3_gpu_shaders.h", "w").write("\n".join(out) + "\n")
print("wrote ps3/source/ps3_gpu_shaders.h")
PYEOF
