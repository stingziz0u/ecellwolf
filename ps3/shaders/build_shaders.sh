#!/bin/sh
#
# Regenerates src/ps3_gpu_shaders.h. NOT part of the normal build: the
# header is in the tree, so building the game needs neither of these tools.
#
# Needs:
#   cgc      NVIDIA Cg Toolkit 3.1, Linux build (apt install nvidia-cg-toolkit)
#   cgcomp   PSL1GHT's, only its assembler mode (-a): $PS3DEV/bin/cgcomp
#   python3
#
# cgc turns Cg into NV40 assembly (profiles vp40 / fp40), cgcomp -a turns
# the assembly into the .vpo/.fpo binaries PSL1GHT loads (the method of
# TyrQuakeCell and Quake2PS3).
#
#   cd ps3/shaders && sh build_shaders.sh

set -e

CGC=${CGC:-cgc}
CGCOMP=${CGCOMP:-$PS3DEV/bin/cgcomp}

command -v "$CGC" >/dev/null 2>&1 || { echo "cgc not found (apt install nvidia-cg-toolkit)"; exit 1; }
[ -x "$CGCOMP" ] || { echo "cgcomp not found at $CGCOMP"; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$CGC" -quiet -profile vp40 -o "$TMP/r3d_vp.asm" r3d_vp.vcg
"$CGCOMP" -a -v "$TMP/r3d_vp.asm" "$TMP/r3d_vp.vpo" >/dev/null

FPS="r3d_fp_world r3d_fp_smooth r3d_fp_rgba r3d_fp_color"
for fp in $FPS; do
	"$CGC" -quiet -profile fp40 -o "$TMP/$fp.asm" $fp.fcg
	"$CGCOMP" -a -f "$TMP/$fp.asm" "$TMP/$fp.fpo" >/dev/null
done

python3 - "$TMP" r3d_vp $FPS <<'PYEOF'
import sys
tmp = sys.argv[1]
names = sys.argv[2:]
out = ["/* ps3_gpu_shaders.h -- GENERATED by shaders/build_shaders.sh, don't edit.",
       " * Compiled RSX programs (cgc vp40/fp40 + PSL1GHT cgcomp -a) of the Cg",
       " * sources in shaders/. */",
       "",
       "#ifndef PS3_GPU_SHADERS_H",
       "#define PS3_GPU_SHADERS_H",
       ""]
for n in names:
    ext = ".vpo" if n.endswith("_vp") else ".fpo"
    data = open(tmp + "/" + n + ext, "rb").read()
    out.append("static const unsigned char %s%s[] __attribute__((aligned(16))) = {" % (n, ext.replace(".", "_")))
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
    out.append("};")
    out.append("")
out.append("#endif")
open("../source/ps3_gpu_shaders.h", "w").write("\n".join(out) + "\n")
print("wrote ps3/source/ps3_gpu_shaders.h")
PYEOF
